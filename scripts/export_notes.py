#!/usr/bin/env python3
"""Export local learning notes into a clean, standalone Markdown portfolio.

Compile profile.md, progress.md, and project-map.md into an organized
study guide and engineering portfolio.
"""

import argparse
from datetime import datetime, timezone
from pathlib import Path
import sys

STATE_DIR_NAMES = (".vibewise", ".vibe-wise", ".not-ur-vibe", ".sensible-vibes")


def find_state_directory(cwd: Path) -> Path:
    for directory in (cwd, *cwd.parents):
        for name in STATE_DIR_NAMES:
            candidate = directory / name
            if candidate.is_dir() and not candidate.is_symlink():
                return candidate
        if (directory / ".git").exists():
            break
    return None


def export_notes(cwd: Path, output_file: Path) -> Path:
    state = find_state_directory(cwd)
    if not state:
        raise FileNotFoundError(f"No active learning state found in {cwd}")

    profile_text = (state / "profile.md").read_text(encoding="utf-8") if (state / "profile.md").exists() else "No profile."
    progress_text = (state / "progress.md").read_text(encoding="utf-8") if (state / "progress.md").exists() else "No progress recorded."
    map_text = (state / "project-map.md").read_text(encoding="utf-8") if (state / "project-map.md").exists() else "No project map."

    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    doc = f"""# Engineering Learning Portfolio & Knowledge Log
*Generated by Not Your Vibe on {timestamp}*

---

## 1. Project Architecture Map

{map_text}

---

## 2. Learner Profile & Mastered Concepts

{profile_text}

---

## 3. Detailed Learning Log & Decision History

{progress_text}

---
*Built with [Not Your Vibe](https://github.com/nykooi1/vibe-wise) - You build. AI writes.*
"""

    output_file.write_text(doc, encoding="utf-8")
    return output_file


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cwd", default=".", help="Project working directory")
    parser.add_argument("--output", default="LEARNING_PORTFOLIO.md", help="Target markdown file")
    args = parser.parse_args()

    cwd = Path(args.cwd).resolve()
    out = Path(args.output).resolve()

    try:
        saved = export_notes(cwd, out)
        print(f"Successfully exported learning portfolio to: {saved}")
        return 0
    except Exception as err:
        print(f"Error exporting notes: {err}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
